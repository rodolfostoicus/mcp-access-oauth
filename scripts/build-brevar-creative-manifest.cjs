// Encode the four reviewed campaign images for immutable public delivery.
// This performs JPEG transport encoding only: no resizing, cropping or redesign.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const [inputDir, outputDir] = process.argv.slice(2);
if (!inputDir || !outputDir) throw new Error('Usage: node scripts/build-brevar-creative-manifest.cjs INPUT_DIR OUTPUT_DIR');
const originals = [
  ['preparo-feed', 'exec-f23c2961-3bd4-45fb-af24-bce01d5c25d1.png'],
  ['fundamentos-feed', 'exec-004c32c0-7208-4233-a3c4-cb0e1c012d22.png'],
  ['preparo-stories', 'exec-3127cb97-5be1-4cc1-8995-d7f476eb0078.png'],
  ['fundamentos-stories', 'exec-b8a34fd7-ce5e-4bb7-a58f-a3ebb27b8f0e.png'],
];
fs.mkdirSync(outputDir, { recursive: true });
const imports = [];
const entries = [];
const index = [];
fs.mkdirSync(path.join(__dirname, '../src/creative-data'), { recursive: true });
for (const [label, original] of originals) {
  const intermediate = path.join(outputDir, label + '.jpg');
  execFileSync('convert', [path.join(inputDir, original), '-strip', '-sampling-factor', '4:4:4', '-quality', '88', intermediate]);
  const bytes = fs.readFileSync(intermediate);
  const digest = crypto.createHash('sha256').update(bytes).digest('hex');
  const filename = `brevar-${label}-${digest.slice(0,16)}.jpg`;
  const pathname = '/creative-assets/' + filename;
  fs.renameSync(intermediate, path.join(outputDir, filename));
  const identifier = 'asset' + index.length;
  fs.writeFileSync(path.join(__dirname, '../src/creative-data', label + '.ts'),
    '// Public BREVAR artwork, JPEG transport encoding. SHA256: ' + digest + '\n' +
    'export default ' + JSON.stringify(bytes.toString('base64')) + ';\n');
  imports.push(`import ${identifier} from "./creative-data/${label}";`);
  entries.push(`  ${JSON.stringify(pathname)}: { mimeType: "image/jpeg", base64: ${identifier} }`);
  index.push({ label, pathname, sha256: digest, bytes: bytes.length, source: original });
}
fs.writeFileSync(path.join(__dirname, '../src/creative-manifest.ts'),
  '// Generated by scripts/build-brevar-creative-manifest.cjs from reviewed BREVAR artwork.\n' +
  '// Public marketing images only. Do not place private data or credentials here.\n' +
  imports.join('\n') + '\n\n' +
  'export const CREATIVE_ASSETS: Record<string, { mimeType: "image/jpeg" | "image/png"; base64: string }> = {\n' +
  entries.join(',\n') + '\n};\n');
fs.writeFileSync(path.join(outputDir, 'index.json'), JSON.stringify(index, null, 2) + '\n');
console.log(JSON.stringify(index));
